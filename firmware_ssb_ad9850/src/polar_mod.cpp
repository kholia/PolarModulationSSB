// 257-tap Hi-Fi Hilbert: dense coefficients + power-of-2 buffer (branchless indexing)
static void __not_in_flash_func(hilbert_f_hifi)(float sample_in, float *i_out, float *q_out) {
  hilbert_history[hilbert_idx] = sample_in;
  float q = 0;
  // 128 multiply-accumulates with sequential coefficient access
  for (int i = 0; i < 128; i++) {
    int k = 2 * i + 1;  // original odd index: 1, 3, 5, ..., 255
    int h_idx = (hilbert_idx - k) & HILBERT_MASK;  // branchless wrap
    q += hilbert_history[h_idx] * h_hifi_nz[i];
  }
  int i_idx = (hilbert_idx - 128) & HILBERT_MASK;
  *i_out = hilbert_history[i_idx];
  *q_out = q;
  hilbert_idx = (hilbert_idx + 1) & HILBERT_MASK;
}
