// Hi-Fi mode: 257-tap Hilbert filter for 50-15000 Hz bandwidth
// SSB narrowband: 127-tap for 300-3000 Hz (Blackman-Harris windowed)
#if USE_HIFI
#define HILBERT_TAPS 257
#define HILBERT_DELAY 128  // (HILBERT_TAPS-1)/2
#define HILBERT_BUF 512    // Power-of-2 buffer for branchless modular indexing
#define HILBERT_MASK 511
#else
#define HILBERT_TAPS 127
#define HILBERT_DELAY 63
#define HILBERT_BUF 128
#define HILBERT_MASK 127
#endif

// Filter delay lines (file-scope for reset access)
static float delay_bp[8] = { 0 };
static float pre_emph_state = 0;
static float hilbert_history[HILBERT_BUF] = { 0 };
static int hilbert_idx = 0;
static float last_angle = 0;
static float dc_state = 0.0f;
static float hp2_delay[2] = {0}; // HIFI 2nd-order HPF at 200Hz (Butterworth)
// P2: Adaptive I/Q gain correction — compensates Hilbert FIR magnitude rolloff
// at band edges (especially near 300 Hz) where Q gain droops relative to I.
static float iq_i_rms = 0.0f;
static float iq_q_rms = 0.0f;
static float iq_q_corr = 1.0f;

void polar_mod_reset(void) {
  for (int i = 0; i < 8; i++) delay_bp[i] = 0;
  pre_emph_state = 0;
  for (int i = 0; i < HILBERT_BUF; i++) hilbert_history[i] = 0;
  hilbert_idx = 0;
  last_angle = 0;
  dc_state = 0.0f;
  hp2_delay[0] = hp2_delay[1] = 0;
  iq_i_rms = 0.0f;
  iq_q_rms = 0.0f;
  iq_q_corr = 1.0f;
}

// Biquad filter implementation (float) — Transposed Direct Form II
static inline float biquad_f(float x, float b0, float b1, float b2, float a1, float a2, float *delay) {
  float y = b0 * x + delay[0];
  delay[0] = b1 * x - a1 * y + delay[1];
  delay[1] = b2 * x - a2 * y;
  return y;
}

// 300Hz-3000Hz Bandpass (2nd order HP + 2nd order LP cascade)
// Used only in non-HiFi SSB voice mode
float __not_in_flash_func(filter_bandpass_16k)(float x) {
#if SAMPLE_RATE == 32000
  // Highpass 300Hz at 32kHz (2nd order Butterworth)
  float s1 = biquad_f(x, 0.9592f, -1.9183f, 0.9592f, -1.9166f, 0.9201f, &delay_bp[0]);
  // Lowpass 3000Hz at 32kHz (2nd order Butterworth)
  float s2 = biquad_f(s1, 0.0609f, 0.1217f, 0.0609f, -1.1930f, 0.4364f, &delay_bp[2]);
#else
  // Highpass 300Hz at 16kHz (2nd order Butterworth)
  float s1 = biquad_f(x, 0.9186f, -1.8372f, 0.9186f, -1.8347f, 0.8408f, &delay_bp[0]);
  // Lowpass 3000Hz at 16kHz (2nd order Butterworth)
  float s2 = biquad_f(s1, 0.2452f, 0.4905f, 0.2452f, -0.1369f, 0.1177f, &delay_bp[2]);
#endif
  return s2;
}

